# Aula 6
# If-Else

# Imports

# Inputs
number=1

name="Tiago"

# Functions
if (number==1):
    print("Numero é igual a 1")
else:
    print("Numero não é igual a 1")

if (number==2):
    print("Numero é igual a 2")
else:
    print("Numero não é igual a 2")


if ("z" in name):
    print("Nome tem a letra z")
elif ("g" in name):
    print("Nome tem a letra g")
else:
    print("Nome não tem a letra g")

# Outputs
print(number)
print(name)